# Markers that must already exist for SCRIPT_ROOT to look like a real,
# previous-version company-knowledge-search project root.
REQUIRED_MARKERS = [
    "app.py",
    "src/config.py",
    "src/search.py",
    "src/database.py",
    "src/models.py",
    "start.bat",
]

# Local corporate data this script must never create, modify, or delete.
# Verified unchanged (by content hash, when present) before declaring
# success.
PROTECTED_FILES = [
    "data/knowledge.db",
    "data/config.json",
]


def log(message: str) -> None:
    print(message, flush=True)


def fail(message: str) -> None:
    log(f"ERROR: {message}")
    sys.exit(1)


def verify_project_root(root: Path) -> None:
    missing = [marker for marker in REQUIRED_MARKERS if not (root / marker).exists()]
    if missing:
        log("ERROR: this does not look like a company-knowledge-search project root.")
        log(f"Expected to find these files next to upgrade_v1.py in {root}:")
        for marker in REQUIRED_MARKERS:
            mark = "OK" if (root / marker).exists() else "MISSING"
            log(f"  [{mark}] {marker}")
        log("")
        log("Copy upgrade_v1.py into the existing company-knowledge-search")
        log("folder (next to app.py) and run it from there.")
        sys.exit(1)
    log("Project root looks valid.")


def hash_file(path: Path):
    if not path.exists():
        return None
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot_protected(root: Path) -> dict:
    snapshot = {}
    for rel in PROTECTED_FILES:
        path = root / rel
        snapshot[rel] = {"existed": path.exists(), "hash": hash_file(path)}
    return snapshot


def verify_protected_unchanged(root: Path, snapshot: dict) -> None:
    for rel, before in snapshot.items():
        path = root / rel
        exists_now = path.exists()
        if before["existed"] and not exists_now:
            raise RuntimeError(f"{rel} is missing after upgrade -- this must never happen.")
        if before["existed"] and exists_now and hash_file(path) != before["hash"]:
            raise RuntimeError(f"{rel} changed during upgrade -- this must never happen.")
        if not before["existed"] and exists_now:
            # The script itself never creates data/config.json or
            # data/knowledge.db; if one now exists, something else (not
            # this script) created it during validation. Treat this as a
            # hard failure so nothing is silently left behind.
            raise RuntimeError(f"{rel} was unexpectedly created during upgrade.")


def compile_check(root: Path, written) -> None:
    for rel, _existed in written:
        if rel.endswith(".py"):
            try:
                py_compile.compile(str(root / rel), doraise=True)
            except py_compile.PyCompileError as exc:
                raise RuntimeError(f"{rel} failed to compile:\n{exc}") from exc
    log("Python syntax check passed for all updated files.")


def sandbox_import_check(root: Path) -> None:
    """Import the updated app + src package in a throwaway copy, completely
    isolated from the real project's data/ and logs/ directories, so this
    check can never touch corporate data."""
    check_code = (
        "import app\n"
        "import src.copilot_prompt as _copilot\n"
        "assert hasattr(_copilot, 'build_copilot_prompt'), 'build_copilot_prompt is missing'\n"
        "import src.formatting as _formatting\n"
        "import src.search as _search\n"
        "import src.database as _database\n"
        "import src.config as _config\n"
        "import src.indexing as _indexing\n"
        "import src.models as _models\n"
        "import src.scanner as _scanner\n"
        "import src.logging_setup as _logging_setup\n"
        "import src.parsers as _parsers\n"
        "print('SANDBOX_IMPORT_OK')\n"
    )
    with tempfile.TemporaryDirectory(prefix="cks_upgrade_check_") as tmp:
        tmp_path = Path(tmp)
        shutil.copy2(root / "app.py", tmp_path / "app.py")
        shutil.copytree(
            root / "src",
            tmp_path / "src",
            ignore=shutil.ignore_patterns("__pycache__"),
        )
        try:
            proc = subprocess.run(
                [sys.executable, "-c", check_code],
                cwd=str(tmp_path),
                capture_output=True,
                text=True,
                timeout=90,
            )
        except subprocess.TimeoutExpired as exc:
            raise RuntimeError("post-upgrade import check timed out after 90s") from exc

    if proc.returncode != 0 or "SANDBOX_IMPORT_OK" not in proc.stdout:
        tail = (proc.stderr or "")[-4000:]
        raise RuntimeError(f"post-upgrade import check failed (exit {proc.returncode}):\n{tail}")
    log("Post-upgrade import check passed (app.py + all src modules).")


def rollback(root: Path, backup_dir: Path, written) -> None:
    log("Restoring previous files from backup...")
    for rel, existed in written:
        dest = root / rel
        if existed:
            backup_src = backup_dir / rel
            if backup_src.exists():
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(backup_src, dest)
                log(f"  restored {rel}")
            else:
                log(f"  WARNING: no backup found for {rel}; left as written (could not roll back safely)")
        else:
            if dest.exists():
                dest.unlink()
                log(f"  removed {rel} (was newly added by this upgrade)")
    log(f"Rollback complete. Your previous installation has been restored.")
    log(f"(A copy of the files this upgrade attempted to write is still in: {backup_dir})")


def main() -> None:
    log("company-knowledge-search upgrade")
    log("=" * 40)

    verify_project_root(SCRIPT_ROOT)

    protected_snapshot = snapshot_protected(SCRIPT_ROOT)
    for rel, info in protected_snapshot.items():
        state = "found" if info["existed"] else "not present (will not be created)"
        log(f"Protecting {rel} ({state}).")

    timestamp = time.strftime("%Y%m%d_%H%M%S")
    backup_dir = SCRIPT_ROOT / f"upgrade_backup_{timestamp}"

    log("")
    log("Writing updated files...")
    written = []
    try:
        for rel, encoded in FILES.items():
            dest = SCRIPT_ROOT / rel
            existed = dest.exists()
            if existed:
                backup_dest = backup_dir / rel
                backup_dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(dest, backup_dest)
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(base64.b64decode(encoded))
            written.append((rel, existed))
            log(f"  {'updated' if existed else 'added  '} {rel}")

        log("")
        log("Validating upgrade...")
        compile_check(SCRIPT_ROOT, written)
        sandbox_import_check(SCRIPT_ROOT)
        verify_protected_unchanged(SCRIPT_ROOT, protected_snapshot)
        log("Local corporate data confirmed untouched (data/knowledge.db, data/config.json).")

    except Exception as exc:  # noqa: BLE001 -- any failure triggers rollback
        log("")
        log(f"VALIDATION FAILED: {exc}")
        log("")
        rollback(SCRIPT_ROOT, backup_dir, written)
        log("")
        log("Upgrade NOT applied. Your installation is unchanged.")
        sys.exit(1)

    log("")
    log("=" * 40)
    log("Upgrade complete.")
    log(f"Backup of replaced files: {backup_dir}")
    log("Next step: run start.bat to restart the app.")


if __name__ == "__main__":
    main()
