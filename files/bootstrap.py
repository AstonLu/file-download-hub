# Directories that exist in the original project even though they start
# out empty (data/ and logs/ are created automatically by the app on
# first run too, via src/config.py + src/logging_setup.py; creating them
# here just makes the freshly-generated layout match immediately).
EMPTY_DIRS = ("data", "logs",)


def decode_file(encoded: str) -> str:
    """Base64 -> UTF-8 text, with line endings normalized to bare "\n"."""
    raw = base64.b64decode(encoded)
    text = raw.decode("utf-8")
    return text.replace("\r\n", "\n")


def write_file(target_root: Path, relative_path: str, encoded_content: str) -> None:
    text = decode_file(encoded_content)
    if relative_path.endswith(".bat"):
        # Batch files are conventionally CRLF on Windows; normalize to
        # that regardless of how the text was stored in this script.
        text = text.replace("\n", "\r\n")
    destination = target_root / relative_path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(text.encode("utf-8"))
    print(f"  wrote {relative_path}")


def main() -> None:
    target_root = Path.cwd() / PROJECT_NAME

    if target_root.exists():
        print(f"ERROR: target folder already exists: {target_root}")
        print("Refusing to overwrite an existing project.")
        print("Remove or rename that folder, or run this script from a different directory, then try again.")
        sys.exit(1)

    print(f"Creating project at: {target_root}")
    target_root.mkdir(parents=True)

    for relative_path, encoded_content in FILES.items():
        write_file(target_root, relative_path, encoded_content)

    for dir_name in EMPTY_DIRS:
        (target_root / dir_name).mkdir(parents=True, exist_ok=True)
        print(f"  created {dir_name}/")

    print()
    print("Project created successfully.")
    print()
    print("Next:")
    print(f"1. cd {PROJECT_NAME}")
    print("2. setup.bat")
    print("3. start.bat")


if __name__ == "__main__":
    main()
